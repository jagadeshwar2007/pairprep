#!/usr/bin/env node
/**
 * Generates the catalog seed migration (branches + subjects) from src/data/academicData.ts,
 * which stays the single source of truth for site navigation.
 *
 *   node scripts/generate-catalog-sql.mjs          # rewrite the migration
 *   node scripts/generate-catalog-sql.mjs --check  # exit 1 if the migration is out of date
 *
 * To add a subject: edit academicData.ts, run this script, and commit the new migration
 * (create a NEW migration file for already-deployed databases; see README).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'src/data/academicData.ts'), 'utf8');
const { outputText } = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
});

const mod = { exports: {} };
// academicData.ts only imports types from '@/types', which erase to nothing.
new Function('exports', 'require', 'module', outputText)(mod.exports, () => ({}), mod);
const { BRANCHES, SUBJECTS } = mod.exports;

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

const lines = [];
lines.push('-- =============================================================================');
lines.push('-- 0006 Catalog seed: branches and subjects');
lines.push('-- GENERATED by scripts/generate-catalog-sql.mjs from src/data/academicData.ts.');
lines.push('-- Do not edit by hand. Re-run the script after changing academicData.ts.');
lines.push('-- =============================================================================');
lines.push('');
lines.push('insert into public.branches (slug, code, name, sort_order) values');
lines.push(
  BRANCHES.map((b, i) => `  (${q(b.id)}, ${q(b.code)}, ${q(b.name)}, ${i})`).join(',\n'),
);
lines.push('on conflict (slug) do update set code = excluded.code, name = excluded.name, sort_order = excluded.sort_order;');
lines.push('');
lines.push('insert into public.subjects (branch_id, academic_year, semester, code, name, slug, credits)');
lines.push('select b.id, v.academic_year, v.semester, v.code, v.name, v.slug, v.credits');
lines.push('from (values');
lines.push(
  SUBJECTS.map(
    (s) =>
      `  (${q(s.branchId)}, ${q(s.yearId)}, ${s.semester}::smallint, ${q(s.code)}, ${q(s.name)}, ${q(s.id)}, ${s.credits ?? 'null'}::smallint)`,
  ).join(',\n'),
);
lines.push(') as v (branch_slug, academic_year, semester, code, name, slug, credits)');
lines.push('join public.branches b on b.slug = v.branch_slug');
lines.push('on conflict (slug) do update set');
lines.push('  branch_id = excluded.branch_id, academic_year = excluded.academic_year, semester = excluded.semester,');
lines.push('  code = excluded.code, name = excluded.name, credits = excluded.credits;');
lines.push('');

const out = lines.join('\n');
const target = join(root, 'supabase/migrations/20261021000006_catalog_seed.sql');

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== out) {
    console.error('Catalog migration is out of date. Run: node scripts/generate-catalog-sql.mjs');
    process.exit(1);
  }
  console.log(`Catalog migration is up to date (${BRANCHES.length} branches, ${SUBJECTS.length} subjects).`);
} else {
  writeFileSync(target, out);
  console.log(`Wrote ${target} (${BRANCHES.length} branches, ${SUBJECTS.length} subjects).`);
}
