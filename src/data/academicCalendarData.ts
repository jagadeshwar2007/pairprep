// Helper functions for UI and Attendance compatibility
export function getEventsForDate(dateStr: string): CalendarEvent[] {
  return OFFICIAL_ACADEMIC_CALENDAR_EVENTS.filter((event) => {
    if (!event.endDate) {
      return event.startDate === dateStr;
    }
    return dateStr >= event.startDate && dateStr <= event.endDate;
  });
}

export function getEventsForMonth(year: number, monthIndex: number): CalendarEvent[] {
  // monthIndex: 0-based (0 = Jan, 11 = Dec)
  const monthStr = `${year}-${(monthIndex + 1).toString().padStart(2, '0')}`;
  return OFFICIAL_ACADEMIC_CALENDAR_EVENTS.filter((event) => {
    const startMonth = event.startDate.slice(0, 7);
    const endMonth = event.endDate ? event.endDate.slice(0, 7) : startMonth;
    return monthStr >= startMonth && monthStr <= endMonth;
  });
}

export function isDateHoliday(dateStr: string): boolean {
  return OFFICIAL_ACADEMIC_CALENDAR_EVENTS.some(
    (e) => e.category === 'holiday' && e.startDate <= dateStr && (e.endDate ? e.endDate >= dateStr : e.startDate === dateStr)
  );
}
